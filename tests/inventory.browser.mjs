import { chromium, expect } from '@playwright/test';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
const snapshot = () => page.evaluate(() => JSON.parse(localStorage.getItem('commons-demo-v1')).state.orgs.find(o => o.id === 'org-ironclad'));
const csv = 'Product,Qty,Unit Price,Vendor\n"Test motor, small",2,14.50,"Parts, Inc"\nTest cable,2.5,,\nTest invalid,-3,5,Shop';
async function upload(text, name = 'inventory.csv') {
  await page.getByRole('button', { name: 'Import CSV', exact: true }).click();
  await page.getByLabel('CSV file').setInputFiles({ name, mimeType: 'text/csv', buffer: Buffer.from(text) });
}
try {
  await page.goto('http://127.0.0.1:5173/#/app/inventory');
  await page.evaluate(async () => { const { useStore } = await import('/src/lib/store.ts'); useStore.getState().setViewAs('org-ironclad', 'maya'); });
  await upload(csv);
  await page.getByLabel('Cost means').selectOption('unit');
  await page.getByLabel('Number format').selectOption('dot');
  await page.getByRole('button', { name: 'Preview records' }).click();
  await expect(page.getByText('3 read · 2 ready · 1 blocked · 0 excluded')).toBeVisible();
  await page.getByLabel('Record 4 Quantity', { exact: true }).fill('0');
  await expect(page.getByText('3 read · 3 ready · 0 blocked · 0 excluded')).toBeVisible();
  await page.getByLabel('I reviewed').check();
  await page.getByRole('button', { name: 'Save 3 records' }).click();
  let org = await snapshot();
  if (org.inventoryImports[0].saved !== 3) throw new Error('Import count mismatch');
  if (org.items.find(i => i.name === 'Test cable').unitCost !== null) throw new Error('Unknown cost changed');
  if (org.items.find(i => i.name === 'Test invalid').qty !== 0) throw new Error('Zero quantity changed');
  await page.reload();
  await page.getByRole('searchbox').fill('Test motor');
  await expect(page.getByText('Test motor, small', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Edit', exact: true }).click();
  await page.getByLabel('Supplier', { exact: true }).fill('Updated supplier');
  await page.getByRole('button', { name: 'Save item', exact: true }).click();
  await page.reload();
  org = await snapshot();
  if (org.items.find(i => i.name === 'Test motor, small').supplier !== 'Updated supplier') throw new Error('Edit not persisted');
  await upload(csv, 'renamed.csv');
  await expect(page.getByText('This file was already imported into this department. Edit the saved records to update stock.')).toBeVisible();
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await upload('Name,Qty\nM3 bolts,1\nBroken,-1');
  await page.getByLabel('Number format').selectOption('dot');
  await page.getByRole('button', { name: 'Preview records' }).click();
  await expect(page.getByText('2 read · 0 ready · 2 blocked · 0 excluded')).toBeVisible();
  await page.getByLabel('Keep as a separate record').check();
  await page.getByLabel('Include record 3').uncheck();
  await page.getByLabel('I reviewed').check();
  await page.getByRole('button', { name: 'Save 1 records' }).click();
  org = await snapshot();
  if (org.inventoryImports[0].excluded !== 1) throw new Error('Exclusion not recorded');
  // A failing storage write must leave the preview intact and avoid claiming success.
  await upload('Name,Qty\nQuota item,1');
  await page.getByLabel('Number format').selectOption('dot');
  await page.getByRole('button', { name: 'Preview records' }).click();
  await page.getByLabel('I reviewed').check();
  await page.evaluate(() => { window.originalSetItem = Storage.prototype.setItem; Storage.prototype.setItem = () => { throw new Error('quota'); }; });
  await page.getByRole('button', { name: 'Save 1 records' }).click();
  await expect(page.getByRole('alert')).toContainText('Could not save');
  await expect(page.getByRole('dialog', { name: 'Import inventory CSV' })).toBeVisible();
  await page.evaluate(() => { Storage.prototype.setItem = window.originalSetItem; });
  await page.getByRole('button', { name: 'Save 1 records' }).click();
  org = await snapshot();
  if (org.items.filter(i => i.name === 'Quota item').length !== 1) throw new Error('Retry duplicated data');
  await page.getByRole('button', { name: '+ Add item', exact: true }).click();
  await page.getByLabel('Name', { exact: true }).fill('Manual item');
  await page.getByLabel('Quantity', { exact: true }).fill('0');
  await page.getByLabel('Unit cost', { exact: true }).fill('0');
  await page.getByRole('button', { name: 'Save item', exact: true }).click();
  org = await snapshot();
  if (org.items.find(i => i.name === 'Manual item').unitCost !== '0.000000') throw new Error('Manual zero cost not preserved');
  await page.evaluate(async () => { const { useStore } = await import('/src/lib/store.ts'); useStore.getState().setViewAs('org-ironclad', 'tom'); });
  await expect(page.getByRole('button', { name: 'Import CSV', exact: true })).toHaveCount(0);
  await page.evaluate(async () => { const { useStore } = await import('/src/lib/store.ts'); useStore.getState().setViewAs('org-ironclad', 'daniel'); });
  await page.getByRole('button', { name: 'Import CSV', exact: true }).click();
  await expect(page.getByLabel('Destination department').locator('option')).toHaveCount(1);
  await expect(page.getByLabel('Destination department')).toHaveValue('Mechanical');
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await page.getByRole('searchbox').fill('');
  await page.screenshot({ path: 'inventory-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'inventory-mobile.png', fullPage: true });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  if (overflow) throw new Error('Mobile page overflow');
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('Browser checks passed: import, correction, duplicates, exclusion, save failure/retry, manual add/edit, reload, department roles, mobile layout.');
} finally { await browser.close(); }
